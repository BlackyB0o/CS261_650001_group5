CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL REFERENCES users(id),
    round_id BIGINT NOT NULL REFERENCES delivery_rounds(id),
    handoff_method VARCHAR(20) NOT NULL,
    handoff_location VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_handoff_method
        CHECK (handoff_method IN ('MEETUP', 'DELIVERY')),

    CONSTRAINT chk_order_status
        CHECK (status IN ('PENDING', 'PAID', 'COMPLETED'))
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL,
    note TEXT,

    CONSTRAINT chk_order_item_quantity
        CHECK (quantity > 0)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),

    product_amount NUMERIC(10,2) NOT NULL,
    service_fee NUMERIC(10,2) NOT NULL,
    total_amount NUMERIC(10,2) NOT NULL,

    payment_method VARCHAR(20) NOT NULL DEFAULT 'QR_TRANSFER',
    qr_payload VARCHAR(255),
    slip_image_url VARCHAR(500),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    transaction_reference VARCHAR(100),
    paid_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_payment_amounts
        CHECK (
            product_amount > 0
            AND service_fee >= 0
            AND total_amount = product_amount + service_fee
        ),

    CONSTRAINT chk_payment_method
        CHECK (payment_method = 'QR_TRANSFER'),

    CONSTRAINT chk_payment_status
        CHECK (payment_status IN ('PENDING', 'HELD', 'FAILED', 'RELEASED'))
);

CREATE TABLE order_completions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL UNIQUE REFERENCES payments(id),
    confirmed_by BIGINT NOT NULL REFERENCES users(id),
    evidence_image_url VARCHAR(500) NOT NULL,
    confirmed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completion_status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',

    CONSTRAINT chk_completion_status
        CHECK (completion_status = 'COMPLETED')
);