CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL REFERENCES users(id),
    round_id BIGINT NOT NULL REFERENCES delivery_rounds(id),
    handoff_method VARCHAR(20) NOT NULL,
    handoff_location VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_handoff_method
        CHECK (handoff_method IN ('MEETUP', 'DELIVERY')),

    CONSTRAINT chk_order_status
        CHECK (status IN ('PENDING', 'PAID', 'COMPLETED'))
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL,
    note TEXT,

    CONSTRAINT chk_order_item_quantity
        CHECK (quantity > 0)
);