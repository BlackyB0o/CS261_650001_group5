CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL REFERENCES users(id),
    round_id BIGINT NOT NULL REFERENCES delivery_rounds(id),
    handoff_method VARCHAR(20) NOT NULL,
    handoff_location VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_handoff_method
        CHECK (handoff_method IN ('MEETUP', 'DELIVERY')),

    CONSTRAINT chk_order_status
        CHECK (status IN (
            'PENDING',
            'PAID',
            'ACCEPTED',
            'PURCHASING',
            'READY_FOR_DELIVERY',
            'DELIVERING',
            'COMPLETED',
            'CANCELLED'
        ))
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL,
    note TEXT,

    CONSTRAINT chk_order_item_quantity
        CHECK (quantity > 0)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),

    product_amount NUMERIC(10,2) NOT NULL,
    service_fee NUMERIC(10,2) NOT NULL,
    total_amount NUMERIC(10,2) NOT NULL,

    payment_method VARCHAR(20) NOT NULL DEFAULT 'QR_TRANSFER',
    qr_payload VARCHAR(255),
    slip_image_url VARCHAR(500),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    transaction_reference VARCHAR(100),
    paid_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_payment_amounts
        CHECK (
            product_amount > 0
            AND service_fee >= 0
            AND total_amount = product_amount + service_fee
        ),

    CONSTRAINT chk_payment_method
        CHECK (payment_method = 'QR_TRANSFER'),

    CONSTRAINT chk_payment_status
        CHECK (payment_status IN ('PENDING', 'HELD', 'FAILED', 'RELEASED'))
);

CREATE TABLE order_completions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL UNIQUE REFERENCES payments(id),
    confirmed_by BIGINT NOT NULL REFERENCES users(id),
    evidence_image_url VARCHAR(500) NOT NULL,
    confirmed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completion_status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',

    CONSTRAINT chk_completion_status
        CHECK (completion_status = 'COMPLETED')
);

-- Task39, Task44 (US05, US06): one row per order status change
CREATE TABLE order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    changed_by BIGINT NOT NULL REFERENCES users(id),
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_status_history_changed
        CHECK (from_status IS NULL OR from_status <> to_status)
);

-- Task49, Task54 (US09, US10): problem reports reviewed by admin
CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    reported_user_id BIGINT NOT NULL REFERENCES users(id),
    category VARCHAR(30) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    evidence_url VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    admin_note VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP,

    CONSTRAINT chk_report_category
        CHECK (category IN (
            'PRODUCT_MISMATCH',
            'DELIVERY_ISSUE',
            'PAYMENT_ISSUE',
            'SUSPICIOUS_BEHAVIOR',
            'OTHER'
        )),

    CONSTRAINT chk_report_status
        CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED')),

    CONSTRAINT chk_report_not_self
        CHECK (reporter_id <> reported_user_id)
);
