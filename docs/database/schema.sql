CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    phone_number VARCHAR(10) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_phone_number 
        CHECK (phone_number ~ '[0-9]{10}$')
);

CREATE TABLE otp_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    otp_hash VARCHAR(255) NOT NULL,
    purpose VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    verified_at TIMESTAMP,
    attempts_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_otp_purpose
        CHECK (purpose IN ('LOGIN', 'RESET_PASSWORD')),

    CONSTRAINT chk_otp_attempts
        CHECK (attempts_count BETWEEN 0 AND 5)


);

CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    buyer_id BIGINT NOT NULL
        REFERENCES users(id),

    post_title VARCHAR(255) NOT NULL,
    shop_name VARCHAR(255) NOT NULL,
    product_detail TEXT NOT NULL,

    quantity INTEGER NOT NULL
        CHECK (quantity > 0),

    carry_fee NUMERIC(10, 2) NOT NULL
        CHECK (carry_fee >= 0),

    desired_date DATE NOT NULL,
    location VARCHAR(255) NOT NULL,

    budget NUMERIC(10, 2)
        CHECK (budget IS NULL OR budget >= 0),

    additional_details TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN (
            'OPEN',
            'ACCEPTED',
            'COMPLETED',
            'CANCELLED'
        )),

    accepted_by BIGINT
        REFERENCES users(id),

    accepted_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_post_acceptance CHECK (
        (accepted_by IS NULL AND accepted_at IS NULL)
        OR
        (accepted_by IS NOT NULL AND accepted_at IS NOT NULL)
    ),

    CONSTRAINT chk_post_not_self_accept CHECK (
        accepted_by IS NULL OR accepted_by <> buyer_id
    )
);
CREATE TABLE delivery_rounds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    runner_id BIGINT NOT NULL
        REFERENCES users(id),

    store_name VARCHAR(255) NOT NULL,
    location_name VARCHAR(255) NOT NULL,

    scheduled_at TIMESTAMP NOT NULL,

    service_fee NUMERIC(10,2) NOT NULL
        CHECK (service_fee >= 0),

    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_delivery_rounds_status
        CHECK (status IN (
            'OPEN',
            'FULL',
            'CLOSED',
            'CANCELLED'
        ))
);
